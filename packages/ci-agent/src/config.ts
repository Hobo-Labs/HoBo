import { create } from "@bufbuild/protobuf";
import { z } from "zod";
import { type AgentConfig, AgentConfigSchema } from "./_generated/agent_pb.js";

/** The agent's write authority. Each mode includes the one before it. */
export const AGENT_MODES = ["observe", "suggest", "apply"] as const;
export type AgentMode = (typeof AGENT_MODES)[number];

export const AGENT_ENGINE_KINDS = [
	"gateway",
	"openai",
	"anthropic",
	"google",
	"openai-compatible",
	"harness",
] as const;
export type AgentEngineKind = (typeof AGENT_ENGINE_KINDS)[number];

export const AGENT_HARNESSES = [
	"claude-code",
	"codex",
	"pi",
	"opencode",
	"grok-build",
] as const;

/**
 * Paths no model output may ever change, whatever a repository configures.
 * A conflict in one abstains the whole merge and leaves it to a person:
 * workflow and agent configuration decide what CI runs and with which
 * credentials, ownership files decide who must review, and a lockfile is
 * regenerated by its package manager, not edited.
 */
export const ALWAYS_PROTECTED_PATHS: readonly string[] = Object.freeze([
	".github/**",
	".hobo/**",
	"**/CODEOWNERS",
	"**/pnpm-lock.yaml",
	"**/package-lock.json",
	"**/npm-shrinkwrap.json",
	"**/yarn.lock",
	"**/bun.lock",
	"**/bun.lockb",
	"**/Cargo.lock",
	"**/go.sum",
	"**/poetry.lock",
	"**/uv.lock",
	"**/Gemfile.lock",
	"**/composer.lock",
]);

const CredentialRef = z
	.string()
	.regex(/^(env|github-secret):[A-Z][A-Z0-9_]{0,63}$/);
const text = (max: number) =>
	z
		.string()
		.min(1)
		.max(max)
		// No control characters.
		.regex(/^\P{Cc}+$/u);
const count = (max: number) => z.number().int().min(1).max(max);

const Engine = z
	.object({
		id: z.string().regex(/^[a-z][a-z0-9-]{0,62}$/),
		kind: z.enum(AGENT_ENGINE_KINDS),
		model: z.string().regex(/^[A-Za-z0-9][A-Za-z0-9._:/-]{0,199}$/),
		credential: CredentialRef.optional(),
		baseUrl: z
			.string()
			.max(2048)
			.regex(/^https:\/\/[^\s?#]+$/)
			.optional(),
	})
	.strict()
	.superRefine((engine, context) => {
		const issue = (message: string) =>
			context.addIssue({ code: "custom", message });
		if (
			(engine.kind === "openai-compatible") !==
			(engine.baseUrl !== undefined)
		)
			issue("baseUrl belongs to openai-compatible engines only");
		if (engine.kind !== "harness") return;
		if (!AGENT_HARNESSES.some((harness) => harness === engine.model))
			issue("unknown harness");
		if (engine.credential !== undefined)
			issue("a harness signs in on its own host");
	});

/** The authored `agent` block of `.hobo/ci.json`. The JSON Schema is built from it. */
export const AgentConfigDocumentSchema = z
	.object({
		mode: z.enum(AGENT_MODES),
		engines: z
			.array(Engine)
			.min(1)
			.max(8)
			.refine(
				(engines) =>
					new Set(engines.map((engine) => engine.id)).size === engines.length,
			),
		queue: z
			.object({
				maxDepth: count(50).optional(),
				maxBatchSize: count(20).optional(),
				maxWaitMinutes: count(10_080).optional(),
				priorityLabels: z.array(text(50)).max(16).optional(),
				rollup: z.boolean().optional(),
				label: text(50).optional(),
			})
			.strict()
			.optional(),
		resolution: z
			.object({
				protectedPaths: z.array(text(200)).max(64).optional(),
				maxConflictedFiles: count(50).optional(),
				maxConflictRegions: count(200).optional(),
				maxFileBytes: count(1_048_576).optional(),
				minConfidence: z.number().min(0).max(1).optional(),
				contextLines: z.number().int().min(0).max(200).optional(),
			})
			.strict()
			.optional(),
		budget: z
			.object({
				maxInputTokens: count(2_000_000).optional(),
				maxOutputTokens: count(200_000).optional(),
				maxTokensPerDay: count(1_000_000_000).optional(),
				timeoutSeconds: count(900).optional(),
				maxResolutionsPerTick: count(20).optional(),
			})
			.strict()
			.optional(),
	})
	.strict()
	// One branch carrying several pull requests is a person's decision to merge.
	.refine((config) => !(config.mode === "apply" && config.queue?.rollup));

declare const parsed: unique symbol;
/** An agent configuration with every default applied. Only `parseAgentConfig` makes one. */
export type ParsedAgentConfig = AgentConfig & {
	readonly mode: AgentMode;
	readonly [parsed]: true;
};

/**
 * Parse the authored block. Defaults are the conservative end of each range,
 * and the built-in protected paths are always part of the result.
 */
export function parseAgentConfig(json: string): ParsedAgentConfig {
	let document: z.infer<typeof AgentConfigDocumentSchema>;
	try {
		if (json.length > 64 * 1024) throw new Error("too large");
		document = AgentConfigDocumentSchema.parse(JSON.parse(json));
	} catch {
		// Repository input can contain arbitrary text. Never put it in an error.
		throw new Error("invalid CI agent configuration");
	}
	const { queue, resolution, budget } = document;
	const config = create(AgentConfigSchema, {
		mode: document.mode,
		engines: document.engines.map((engine) => ({
			id: engine.id,
			kind: engine.kind,
			model: engine.model,
			credential: engine.credential ?? "",
			baseUrl: engine.baseUrl ?? "",
		})),
		queue: {
			maxDepth: queue?.maxDepth ?? 20,
			maxBatchSize: queue?.maxBatchSize ?? 4,
			maxWaitMinutes: queue?.maxWaitMinutes ?? 240,
			priorityLabels: queue?.priorityLabels ?? [],
			rollup: queue?.rollup ?? false,
			label: queue?.label ?? "hobo-queue",
		},
		resolution: {
			protectedPaths: [
				...new Set([
					...ALWAYS_PROTECTED_PATHS,
					...(resolution?.protectedPaths ?? []),
				]),
			],
			maxConflictedFiles: resolution?.maxConflictedFiles ?? 5,
			maxConflictRegions: resolution?.maxConflictRegions ?? 20,
			maxFileBytes: resolution?.maxFileBytes ?? 262_144,
			minConfidence: resolution?.minConfidence ?? 0.8,
			contextLines: resolution?.contextLines ?? 12,
		},
		budget: {
			maxInputTokens: budget?.maxInputTokens ?? 60_000,
			maxOutputTokens: budget?.maxOutputTokens ?? 8_000,
			maxTokensPerDay: BigInt(budget?.maxTokensPerDay ?? 2_000_000),
			timeoutSeconds: budget?.timeoutSeconds ?? 120,
			maxResolutionsPerTick: budget?.maxResolutionsPerTick ?? 2,
		},
	});
	// SAFETY: the document parsed above fixes `mode` to an AgentMode, and this is the only place the brand is applied.
	return Object.freeze(config) as ParsedAgentConfig;
}

/** The policy blocks of a parsed configuration; a parsed configuration always has them. */
export function agentPolicies(config: ParsedAgentConfig) {
	const { queue, resolution, budget } = config;
	if (!queue || !resolution || !budget)
		throw new Error("invalid CI agent configuration");
	return { queue, resolution, budget };
}

function globPattern(glob: string): RegExp {
	let source = "";
	for (let index = 0; index < glob.length; index++) {
		const character = glob.charAt(index);
		if (character === "*" && glob.charAt(index + 1) === "*") {
			// `**/` also matches no directory at all; a trailing `**` matches the rest.
			const slash = glob.charAt(index + 2) === "/";
			source += slash ? "(?:.*/)?" : ".*";
			index += slash ? 2 : 1;
		} else if (character === "*") source += "[^/]*";
		else if (character === "?") source += "[^/]";
		else source += character.replace(/[.+^${}()|[\]\\]/g, "\\$&");
	}
	return new RegExp(`^${source}$`);
}

/** Whether a repository-relative path matches any glob (`**`, `*`, `?`). */
export function matchesAnyPath(
	path: string,
	globs: readonly string[],
): boolean {
	return globs.some((glob) => globPattern(glob).test(path));
}
