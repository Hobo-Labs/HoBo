export type TestHarnessErrorCode =
	| "HARNESS_ALIAS_UNKNOWN"
	| "HARNESS_BINDLE_INVALID"
	| "HARNESS_CAMP_DEPLOYMENT_INVALID"
	| "HARNESS_CAMP_DRIVER_REQUIRED"
