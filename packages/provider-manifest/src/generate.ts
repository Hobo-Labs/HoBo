/**
 * Generators over a parsed API spec: a TypeScript client, a code-mode MCP
 * server, and MCP client configuration.
 *
 * Every function here is pure — source text in, source text out. Writing
 * files is the CLI's job.
 */
import type {
	ApiSection,
	McpServer,
} from "./_generated/provider_manifest_pb.js";
import type { ApiOperation, ParsedApiSpec } from "./openapi.js";

const GENERATED_BY = "Generated by @hobo/provider-manifest. Do not edit.";

function comment(value: string): string {
	return value.replace(/\s+/gu, " ").replace(/\*\//gu, "* /").trim();
}

/** A template-literal expression for a path with `{param}` placeholders. */
function pathExpression(path: string): string {
	const literal = (segment: string) => segment.replace(/[\\`$]/gu, "\\$&");
	const parts = path.split(/\{([^}]+)\}/u);
	return `\`${parts
		.map((part, index) =>
			index % 2 === 0
				? literal(part)
				: `\${encodeURIComponent(String(args[${JSON.stringify(part)}]))}`,
		)
		.join("")}\``;
}

function record(operation: ApiOperation, location: "query" | "header") {
	const entries = operation.parameters
		.filter((parameter) => parameter.in === location)
		.map(
			(parameter) =>
				`${JSON.stringify(parameter.name)}: args[${JSON.stringify(parameter.name)}]`,
		);
	return `{ ${entries.join(", ")} }`;
}

/** `api.getPet({ petId, verbose? })` — the call shape shown to a model. */
export function operationSignature(operation: ApiOperation): string {
	const fields = operation.parameters.map(
		(parameter) => `${parameter.name}${parameter.required ? "" : "?"}`,
	);
	if (operation.body !== "none") {
		fields.push(operation.body === "required" ? "body" : "body?");
	}
	return `api.${operation.id}({ ${fields.join(", ")} })`;
}

function methodSource(operation: ApiOperation): string {
	const fields = operation.parameters.map(
		(parameter) =>
			`${JSON.stringify(parameter.name)}${parameter.required ? "" : "?"}: Scalar`,
	);
	if (operation.body !== "none") {
		fields.push(`body${operation.body === "required" ? "" : "?"}: unknown`);
	}
	const needsArgs =
		operation.body === "required" ||
		operation.parameters.some((parameter) => parameter.required);
	const summary = comment(operation.summary);
	return [
		`\t\t/** ${summary === "" ? "" : `${summary} — `}${operation.method} ${comment(operation.path)} */`,
		`\t\t${operation.id}(args: { ${fields.join("; ")} }${needsArgs ? "" : " = {}"}): Promise<unknown> {`,
		`\t\t\treturn request(${JSON.stringify(operation.method)}, ${pathExpression(operation.path)}, ${record(operation, "query")}, ${record(operation, "header")}, ${operation.body === "none" ? "undefined" : "args.body"});`,
		"\t\t},",
	].join("\n");
}

/**
 * A dependency-free TypeScript client: one method per operation over `fetch`.
 * Parameters are named and required-ness is typed; bodies and responses are
 * `unknown`, because schemas are not interpreted.
 */
export function generateApiClient(api: ParsedApiSpec): string {
	return `// ${GENERATED_BY}
// Source: ${comment(api.title)} ${comment(api.version)}

export type Scalar = string | number | boolean;

export type ClientOptions = {
	/** Overrides the server URL declared by the spec. */
	baseUrl?: string;
	/** Extra headers on every request, e.g. Authorization. */
	headers?: Record<string, string>;
	fetch?: typeof fetch;
};

export class ApiError extends Error {
	constructor(
		readonly status: number,
		readonly body: unknown,
	) {
		super(\`request failed with status \${status}\`);
		this.name = "ApiError";
	}
}

export function createClient(options: ClientOptions = {}) {
	const baseUrl = (options.baseUrl ?? ${JSON.stringify(api.baseUrl)}).replace(/\\/+$/u, "");
	const send = options.fetch ?? fetch;

	async function request(
		method: string,
		path: string,
		query: Record<string, Scalar | undefined>,
		headers: Record<string, Scalar | undefined>,
		body: unknown,
	): Promise<unknown> {
		const url = new URL(baseUrl + path);
		for (const [name, value] of Object.entries(query)) {
			if (value !== undefined) url.searchParams.set(name, String(value));
		}
		const merged = new Headers(options.headers);
		for (const [name, value] of Object.entries(headers)) {
			if (value !== undefined) merged.set(name, String(value));
		}
		const init: RequestInit = { method, headers: merged };
		if (body !== undefined) {
			merged.set("content-type", "application/json");
			init.body = JSON.stringify(body);
		}
		const response = await send(url, init);
		const payload = (response.headers.get("content-type") ?? "").includes("json")
			? await response.json()
			: await response.text();
		if (!response.ok) throw new ApiError(response.status, payload);
		return payload;
	}

	return {
${api.operations.map(methodSource).join("\n")}
	};
}

export type Client = ReturnType<typeof createClient>;
`;
}

// The code-mode server's runtime. Plain ESM JavaScript with no dependencies,
// written without template literals so it embeds here verbatim.
const CODE_MODE_RUNTIME = String.raw`
import { spawn } from "node:child_process";
import { createInterface } from "node:readline";

const BASE_URL = (process.env.API_BASE_URL || API.baseUrl).replace(/\/+$/, "");
const TOKEN = process.env.API_TOKEN || "";
const AUTH_HEADER = process.env.API_AUTH_HEADER || "Authorization";
const AUTH_PREFIX = process.env.API_AUTH_PREFIX === undefined ? "Bearer " : process.env.API_AUTH_PREFIX;
const TIMEOUT_MS = Number(process.env.CODE_TIMEOUT_MS || 30000);
const OPERATIONS = new Map(API.operations.map((operation) => [operation.id, operation]));

// The request is built here, in the parent, from the operation table: model
// code never sees the credential and cannot pick the host.
async function callOperation(id, args) {
	const operation = OPERATIONS.get(id);
	if (!operation) throw new Error("unknown operation " + id);
	if (!BASE_URL) throw new Error("no server URL: set API_BASE_URL");
	const input = args && typeof args === "object" ? args : {};
	let path = operation.path;
	const url = new URL(BASE_URL);
	const headers = {};
	for (const parameter of operation.parameters) {
		const value = input[parameter.name];
		if (value === undefined || value === null) {
			if (parameter.required) throw new Error(id + " requires " + parameter.name);
			continue;
		}
		if (parameter.in === "path") path = path.split("{" + parameter.name + "}").join(encodeURIComponent(String(value)));
		else if (parameter.in === "query") url.searchParams.set(parameter.name, String(value));
		else headers[parameter.name] = String(value);
	}
	url.pathname = url.pathname.replace(/\/+$/, "") + path;
	if (TOKEN) headers[AUTH_HEADER] = AUTH_PREFIX + TOKEN;
	const init = { method: operation.method, headers };
	if (operation.body !== "none" && input.body !== undefined) {
		headers["content-type"] = "application/json";
		init.body = JSON.stringify(input.body);
	} else if (operation.body === "required") {
		throw new Error(id + " requires body");
	}
	const response = await fetch(url, init);
	const type = response.headers.get("content-type") || "";
	const body = type.includes("json") ? await response.json() : await response.text();
	return { status: response.status, ok: response.ok, body };
}

// Model-written code runs in a separate Node process started with the
// permission model on: no filesystem, no child processes, no workers, an empty
// environment. It reaches the API only by asking this process over IPC.
const CHILD = [
	"const pending = new Map(); let seq = 0;",
	"function call(op, args) { return new Promise((resolve, reject) => { const id = ++seq; pending.set(id, { resolve, reject }); process.send({ type: 'call', id, op, args }); }); }",
	"process.on('message', async (message) => {",
	"  if (message.type === 'reply') { const waiter = pending.get(message.id); pending.delete(message.id); if (message.error) waiter.reject(new Error(message.error)); else waiter.resolve(message.value); return; }",
	"  const api = {}; for (const op of message.ops) api[op] = (args) => call(op, args || {});",
	"  try { const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor; const value = await new AsyncFunction('api', message.code)(api); process.send({ type: 'done', value: value === undefined ? null : value }); }",
	"  catch (error) { process.send({ type: 'done', error: String((error && error.message) || error) }); }",
	"});",
].join("\n");

function execute(code) {
	return new Promise((resolve, reject) => {
		const child = spawn(process.execPath, ["--permission", "-e", CHILD], {
			env: {},
			stdio: ["ignore", "ignore", "ignore", "ipc"],
		});
		const timer = setTimeout(() => finish(new Error("timed out after " + TIMEOUT_MS + "ms")), TIMEOUT_MS);
		let settled = false;
		function finish(error, value) {
			if (settled) return;
			settled = true;
			clearTimeout(timer);
			child.kill("SIGKILL");
			if (error) reject(error); else resolve(value);
		}
		child.on("error", (error) => finish(error));
		child.on("exit", (status) => finish(new Error("sandbox exited (" + status + "); Node 22.13 or newer is required")));
		child.on("message", (message) => {
			if (message.type === "done") {
				if (message.error) finish(new Error(message.error)); else finish(undefined, message.value);
				return;
			}
			callOperation(message.op, message.args).then(
				(value) => child.send({ type: "reply", id: message.id, value }),
				(error) => child.send({ type: "reply", id: message.id, error: String(error.message || error) }),
			);
		});
		child.send({ type: "run", code, ops: [...OPERATIONS.keys()] });
	});
}

function search(query) {
	const terms = String(query || "").toLowerCase().split(/\s+/).filter(Boolean);
	return API.operations
		.filter((operation) => {
			const haystack = (operation.id + " " + operation.method + " " + operation.path + " " + operation.summary).toLowerCase();
			return terms.every((term) => haystack.includes(term));
		})
		.slice(0, 50)
		.map((operation) => operation.signature + " — " + operation.method + " " + operation.path + (operation.summary ? " — " + operation.summary : ""));
}

const TOOLS = [
	{
		name: "search",
		description: "Find operations of the " + API.title + " API. Returns call signatures to use inside execute. An empty query lists everything.",
		inputSchema: { type: "object", properties: { query: { type: "string" } } },
	},
	{
		name: "execute",
		description: "Run JavaScript against the " + API.title + " API. The code is the body of an async function with one binding, api; each operation is api.<name>(args) and resolves to { status, ok, body }. Return the value you want back. Chain calls, loop and filter here instead of making one tool call per request.",
		inputSchema: { type: "object", properties: { code: { type: "string" } }, required: ["code"] },
	},
];

async function callTool(name, args) {
	if (name === "search") {
		const found = search(args.query);
		return { content: [{ type: "text", text: found.length ? found.join("\n") : "no matching operations" }] };
	}
	if (name === "execute") {
		try {
			const value = await execute(String(args.code || ""));
			return { content: [{ type: "text", text: JSON.stringify(value, null, 2) }] };
		} catch (error) {
			return { isError: true, content: [{ type: "text", text: String(error.message || error) }] };
		}
	}
	throw new Error("unknown tool " + name);
}

async function handle(request) {
	switch (request.method) {
		case "initialize":
			return {
				protocolVersion: (request.params && request.params.protocolVersion) || "2025-06-18",
				capabilities: { tools: {} },
				serverInfo: { name: API.id + "-code-mode", version: API.version || "0.0.0" },
			};
		case "ping":
			return {};
		case "tools/list":
			return { tools: TOOLS };
		case "tools/call":
			return callTool(request.params.name, request.params.arguments || {});
		default:
			throw Object.assign(new Error("method not found: " + request.method), { code: -32601 });
	}
}

// MCP stdio transport: one JSON-RPC message per line.
createInterface({ input: process.stdin }).on("line", async (line) => {
	if (!line.trim()) return;
	let request;
	try {
		request = JSON.parse(line);
	} catch {
		process.stdout.write(JSON.stringify({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "parse error" } }) + "\n");
		return;
	}
	if (request.id === undefined) return;
	try {
		const result = await handle(request);
		process.stdout.write(JSON.stringify({ jsonrpc: "2.0", id: request.id, result }) + "\n");
	} catch (error) {
		process.stdout.write(JSON.stringify({ jsonrpc: "2.0", id: request.id, error: { code: error.code || -32603, message: String(error.message || error) } }) + "\n");
	}
});
`;

/**
 * A code-mode MCP server for an API: instead of one tool per endpoint it
 * exposes `search` (find operations) and `execute` (run model-written
 * JavaScript against a typed `api` object). Output is one dependency-free
 * ESM file speaking MCP over stdio.
 */
export function generateCodeModeServer(id: string, api: ParsedApiSpec): string {
	const table = {
		id,
		title: api.title,
		version: api.version,
		baseUrl: api.baseUrl,
		operations: api.operations.map((operation) => ({
			...operation,
			signature: operationSignature(operation),
		})),
	};
	return `#!/usr/bin/env node
// ${GENERATED_BY}
// Code-mode MCP server for ${comment(api.title)} ${comment(api.version)}.
// Configure with API_TOKEN (and API_BASE_URL, API_AUTH_HEADER, API_AUTH_PREFIX).

const API = ${JSON.stringify(table, null, "\t")};
${CODE_MODE_RUNTIME}`;
}

export type McpClientConfig = {
	readonly mcpServers: Readonly<
		Record<
			string,
			| { readonly type: "http" | "sse"; readonly url: string }
			| { readonly command: string; readonly args: readonly string[] }
		>
	>;
};

function remoteServer(server: McpServer) {
	return {
		type: server.transport === "sse" ? ("sse" as const) : ("http" as const),
		url: server.url,
	};
}

/**
 * `.mcp.json`-shaped client configuration: the provider's own MCP servers,
 * plus any generated code-mode servers (by the file name they were written to).
 */
export function generateMcpClientConfig(
	api: ApiSection | undefined,
	generatedServers: Readonly<Record<string, string>> = {},
): McpClientConfig {
	return {
		mcpServers: Object.fromEntries([
			...(api?.mcpServers ?? []).map(
				(server) => [server.id, remoteServer(server)] as const,
			),
			...Object.entries(generatedServers).map(
				([id, file]) => [id, { command: "node", args: [`./${file}`] }] as const,
			),
		]),
	};
}
