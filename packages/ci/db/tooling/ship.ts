/**
 * The migrations a package ships to its hosts.
 *
 * `db/migrations/` is what is reviewed, and it is not part of what a package
 * publishes or a function bundle carries. A host that prepares a database at
 * run time (the hosted relay's fleet, for its standbys) still has to apply
 * exactly that SQL, so each package carries it as a module:
 * `src/_generated-assets/schema-migrations.ts`, the loaded and digest-checked
 * migration set, written here from the journal and its SQL files.
 *
 * It is a copy, so it is held to its source. `db:generate` rewrites it with
 * every new migration, `db:ship` rewrites it on its own, and `db:check` (and
 * the test suite, with no database) fails when the module is missing or is not
 * what `db/migrations/` loads to. Nobody edits it.
 */

import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import type { SchemaMigrationSet } from "../../src/schema-migrations.js";
import { loadMigrationSet, serializeJson } from "./journal.js";

/** The module a package ships, as its `db/source.ts` imports it. */
export interface ShippedMigrationsModule {
	readonly schemaMigrations?: SchemaMigrationSet;
}

export interface ShippedMigrationsSource {
	/** Recorded with every applied migration; the owning package's name. */
	readonly scope: string;
	/** The package root, as a directory URL; the module is written under it. */
	readonly packageRoot: URL;
	/** `db/migrations/`, which the module is a copy of. */
	readonly directory: URL;
	readonly loadShipped: () => Promise<ShippedMigrationsModule>;
}

const SHIPPED_MODULE = "src/_generated-assets/schema-migrations.ts";
/** The package that owns the runner and the type the module is checked against. */
const RUNNER_PACKAGE = "@hobo/ci";

function shippedLocation(source: ShippedMigrationsSource): URL {
	return new URL(SHIPPED_MODULE, source.packageRoot);
}

/** The module's text, formatted as the repository formats every source file. */
export async function renderShippedMigrations(
	source: ShippedMigrationsSource,
): Promise<{
	readonly location: URL;
	readonly text: string;
	readonly migrations: number;
}> {
	const set = await loadMigrationSet(source.directory);
	const location = shippedLocation(source);
	const runner =
		source.scope === RUNNER_PACKAGE
			? "../schema-migrations.js"
			: `${RUNNER_PACKAGE}/schema-migrations`;
	const draft = [
		"// Generated by `pnpm run db:generate` (or `db:ship`) from db/migrations. Do not edit.",
		`import type { SchemaMigrationSet } from ${JSON.stringify(runner)};`,
		"",
		`/** ${source.scope}'s checked-in migrations, exactly as \`db/migrations/\` loads them. */`,
		`export const schemaMigrations: SchemaMigrationSet = ${JSON.stringify(set, null, "\t")};`,
		"",
	].join("\n");
	const text = execFileSync(
		process.execPath,
		[
			createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome"),
			"format",
			`--stdin-file-path=${fileURLToPath(location)}`,
		],
		{
			cwd: new URL("../../../../", import.meta.url),
			input: draft,
			encoding: "utf8",
		},
	);
	return { location, text, migrations: set.migrations.length };
}

/**
 * Every way the shipped module differs from `db/migrations/`. Empty means a
 * host applies the same statements, digests and violations queries, in the
 * same order and under the same locks, as `db:migrate` does from the files.
 */
export async function checkShippedMigrations(
	source: ShippedMigrationsSource,
): Promise<string[]> {
	let shipped: SchemaMigrationSet | undefined;
	try {
		shipped = (await source.loadShipped()).schemaMigrations;
	} catch {
		shipped = undefined;
	}
	if (shipped === undefined)
		return [`${SHIPPED_MODULE} is missing; run db:ship`];
	const checkedIn = await loadMigrationSet(source.directory);
	return serializeJson(shipped) === serializeJson(checkedIn)
		? []
		: [`${SHIPPED_MODULE} is not what db/migrations loads to; run db:ship`];
}
